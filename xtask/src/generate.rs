//! `cargo xtask gen`: compile `kytrix/**/*.proto` into the `src/kytrix.*.rs`
//! files that `src/lib.rs` pulls in with `include!`.
//!
//! The proto tree is the input, `src/` is the output, and both are checked in:
//! regenerating on an unchanged tree must produce an empty `git diff`.

use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use prost::Message as _;
use prost_types::{DescriptorProto, FileDescriptorSet};

/// Attribute applied to the types that downstream code (de)serialises as JSON.
const SERDE_DERIVE: &str = "#[derive(serde::Serialize, serde::Deserialize)]";

/// Fully qualified proto names that carry [`SERDE_DERIVE`].
///
/// `prost_build` matches these by path prefix, so naming a top-level message
/// also covers its nested messages and `oneof` enums. Only types that actually
/// need JSON get the derive; everything else stays plain prost.
///
/// The prefix must follow the proto package: it moved to `.kytrix.types.v1` when
/// the types were restructured, and a stale prefix matches nothing *silently*.
/// [`verify_serde_types`] is what turns that into an error.
const SERDE_TYPES: &[&str] = &[
    ".kytrix.types.v1.CoinMarketCapFearAndGreedIndex",
    ".kytrix.types.v1.CoinMarketCapFearAndGreedIndexPoint",
    ".kytrix.types.v1.CryptocurrencyETF",
    ".kytrix.types.v1.EthereumWalletEvent",
    ".kytrix.types.v1.EthereumWalletSelection",
    ".kytrix.types.v1.FinancialIndexCategory",
    ".kytrix.types.v1.FinancialIndexDefinition",
    ".kytrix.types.v1.FinancialIndexLocalizedName",
    ".kytrix.types.v1.FinancialIndices",
    ".kytrix.types.v1.PentagonPizzaIndex",
    ".kytrix.types.v1.SolanaWalletEvent",
    ".kytrix.types.v1.SolanaWalletSelection",
    ".kytrix.types.v1.XPost",
    ".kytrix.types.v1.XPostMedia",
    ".kytrix.types.v1.XPostTextSegment",
    ".kytrix.types.v1.XPosts",
    ".kytrix.types.v1.XUserProfile",
    ".kytrix.types.v1.XUserSelection",
];

/// First line of every file `prost_build` emits. Used to recognise the files
/// this task owns before deleting anything out of `src/`.
const GENERATED_HEADER: &str = "// This file is @generated by prost-build.";

pub fn run(args: &[String]) -> Result<(), Box<dyn Error>> {
    let mut check = false;
    for arg in args {
        match arg.as_str() {
            "--check" => check = true,
            other => {
                return Err(format!(
                    "unexpected argument `{other}`; usage: cargo xtask gen [--check]"
                )
                .into());
            }
        }
    }

    let root = repo_root()?;
    let proto_root = root.join("kytrix");
    let src_dir = root.join("src");

    let protos = collect_protos(&proto_root)?;
    if protos.is_empty() {
        return Err(format!("no .proto files under {}", proto_root.display()).into());
    }

    // Generate into `target/` first: `--check` never touches `src/`, and `gen`
    // only writes once every file has been produced successfully.
    let staging = root.join("target").join("xtask").join("gen");
    if staging.exists() {
        fs::remove_dir_all(&staging)?;
    }
    let generation = generate(&protos, &proto_root, &staging)?;
    let generated = &generation.files;

    if check {
        warn_unreferenced(&src_dir, generated)?;
        return compare(&staging, &src_dir, generated);
    }

    for name in generated {
        fs::copy(staging.join(name), src_dir.join(name))?;
    }
    let removed = prune_stale(&src_dir, generated)?;
    warn_unreferenced(&src_dir, generated)?;

    println!(
        "generated {} file(s) from {} proto file(s) into {}/ (serde on {} generated type(s))",
        generated.len(),
        protos.len(),
        display_rel(&src_dir, &root),
        generation.serde_types,
    );
    for name in removed {
        println!("removed stale src/{name}");
    }
    Ok(())
}

/// What a single run of [`generate`] produced.
struct Generation {
    /// File names written to the output directory, sorted.
    files: Vec<String>,
    /// How many generated types actually ended up with [`SERDE_DERIVE`].
    serde_types: usize,
}

/// Runs `prost_build` over `protos`, validates the serde whitelist, and returns
/// the files it wrote.
fn generate(
    protos: &[PathBuf],
    proto_root: &Path,
    out_dir: &Path,
) -> Result<Generation, Box<dyn Error>> {
    fs::create_dir_all(out_dir)?;

    // Keep the descriptor set: it is the only way to tell whether the serde
    // whitelist still points at types that exist.
    let descriptor_path = out_dir.join("descriptor-set.bin");

    let mut config = prost_build::Config::new();
    for ty in SERDE_TYPES {
        config.type_attribute(ty, SERDE_DERIVE);
    }
    config.out_dir(out_dir);
    config.file_descriptor_set_path(&descriptor_path);
    config.compile_protos(protos, &[proto_root])?;

    let descriptor_set = FileDescriptorSet::decode(fs::read(&descriptor_path)?.as_slice())?;
    fs::remove_file(&descriptor_path)?;
    verify_serde_types(&descriptor_set)?;

    let files = generated_files(out_dir)?;
    let serde_types = count_serde_derives(out_dir, &files)?;
    Ok(Generation { files, serde_types })
}

/// Fails if a [`SERDE_TYPES`] entry matches no type in the compiled protos.
///
/// `prost_build` ignores unmatched paths without a word, so a package rename
/// silently drops every derive; this turns that into a hard error.
fn verify_serde_types(descriptor_set: &FileDescriptorSet) -> Result<(), Box<dyn Error>> {
    let mut names = Vec::new();
    for file in &descriptor_set.file {
        let prefix = format!(".{}", file.package());
        for message in &file.message_type {
            collect_type_names(&prefix, message, &mut names);
        }
        for enumeration in &file.enum_type {
            names.push(format!("{prefix}.{}", enumeration.name()));
        }
    }

    let dead: Vec<&str> = SERDE_TYPES
        .iter()
        .copied()
        .filter(|ty| {
            !names
                .iter()
                .any(|name| name == ty || name.starts_with(&format!("{ty}.")))
        })
        .collect();

    if dead.is_empty() {
        return Ok(());
    }

    Err(format!(
        "SERDE_TYPES entries match no proto type:\n  {}\n\
         Check the package prefix: prost-build ignores paths that match nothing.",
        dead.join("\n  ")
    )
    .into())
}

/// Records `message` and, recursively, everything nested inside it.
fn collect_type_names(prefix: &str, message: &DescriptorProto, names: &mut Vec<String>) {
    let fqn = format!("{prefix}.{}", message.name());
    names.push(fqn.clone());
    for nested in &message.nested_type {
        collect_type_names(&fqn, nested, names);
    }
    for enumeration in &message.enum_type {
        names.push(format!("{fqn}.{}", enumeration.name()));
    }
}

fn count_serde_derives(dir: &Path, files: &[String]) -> Result<usize, Box<dyn Error>> {
    let mut count = 0;
    for name in files {
        count += read_text(&dir.join(name))?.matches(SERDE_DERIVE).count();
    }
    Ok(count)
}

/// Reports every difference between a fresh generation and the checked-in `src/`.
fn compare(
    gen_dir: &Path,
    src_dir: &Path,
    generated: &[String],
) -> Result<(), Box<dyn Error>> {
    let mut problems = Vec::new();

    for name in generated {
        let expected = read_text(&gen_dir.join(name))?;
        match read_text(&src_dir.join(name)) {
            Ok(actual) if actual == expected => {}
            Ok(actual) => problems.push(format!(
                "modified: src/{name} ({})",
                describe_diff(&expected, &actual)
            )),
            Err(err) if err.kind() == std::io::ErrorKind::NotFound => {
                problems.push(format!("missing:  src/{name}"));
            }
            Err(err) => return Err(err.into()),
        }
    }

    for name in generated_files(src_dir)? {
        if !generated.iter().any(|generated| generated == &name) {
            problems.push(format!("stale:    src/{name} (no longer generated)"));
        }
    }

    if problems.is_empty() {
        println!("src/ is up to date ({} file(s) checked)", generated.len());
        return Ok(());
    }

    eprintln!("src/ does not match kytrix/:");
    for problem in &problems {
        eprintln!("  {problem}");
    }
    Err("run `cargo xtask gen` and commit the result".into())
}

/// Deletes `src/kytrix.*.rs` files that the current proto tree no longer
/// produces, and returns their names.
fn prune_stale(src_dir: &Path, generated: &[String]) -> Result<Vec<String>, Box<dyn Error>> {
    let mut removed = Vec::new();
    for name in generated_files(src_dir)? {
        if !generated.iter().any(|generated| generated == &name) {
            fs::remove_file(src_dir.join(&name))?;
            removed.push(name);
        }
    }
    Ok(removed)
}

/// Warns about generated files that `src/lib.rs` does not pull in. A proto with a
/// new package produces a new file, and forgetting the `include!` would silently
/// hide the types from the crate.
fn warn_unreferenced(src_dir: &Path, generated: &[String]) -> Result<(), Box<dyn Error>> {
    let lib = read_text(&src_dir.join("lib.rs"))?;
    for name in generated {
        if !lib.contains(&format!("include!(\"{name}\")")) {
            println!("warning: src/{name} is not included by src/lib.rs");
        }
    }
    Ok(())
}

/// Names of the files in `dir` that were produced by `prost_build`.
///
/// `src/` also holds hand-written files such as `lib.rs`; the generated header
/// is what separates the two.
fn generated_files(dir: &Path) -> Result<Vec<String>, Box<dyn Error>> {
    let mut names = Vec::new();
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if !path.extension().is_some_and(|ext| ext == "rs") {
            continue;
        }
        if fs::read_to_string(&path)?.starts_with(GENERATED_HEADER)
            && let Some(name) = path.file_name()
        {
            names.push(name.to_string_lossy().into_owned());
        }
    }
    names.sort();
    Ok(names)
}

fn describe_diff(expected: &str, actual: &str) -> String {
    let expected: Vec<&str> = expected.lines().collect();
    let actual: Vec<&str> = actual.lines().collect();

    // Line-level LCS, so an insertion does not report every later line as changed.
    let mut lcs = vec![vec![0u32; actual.len() + 1]; expected.len() + 1];
    for i in (0..expected.len()).rev() {
        for j in (0..actual.len()).rev() {
            lcs[i][j] = if expected[i] == actual[j] {
                lcs[i + 1][j + 1] + 1
            } else {
                lcs[i + 1][j].max(lcs[i][j + 1])
            };
        }
    }

    let (mut i, mut j) = (0, 0);
    let (mut added, mut removed) = (0, 0);
    let mut first_change = None;
    while i < expected.len() && j < actual.len() {
        if expected[i] == actual[j] {
            i += 1;
            j += 1;
        } else if lcs[i + 1][j] >= lcs[i][j + 1] {
            first_change.get_or_insert(i + 1);
            removed += 1;
            i += 1;
        } else {
            first_change.get_or_insert(i + 1);
            added += 1;
            j += 1;
        }
    }
    removed += expected.len() - i;
    added += actual.len() - j;

    match first_change {
        Some(line) => format!(
            "{removed} line(s) missing from src/, {added} line(s) unexpected in src/, first change at line {line}"
        ),
        None => "differs only in trailing whitespace".to_owned(),
    }
}

fn collect_protos(proto_root: &Path) -> Result<Vec<PathBuf>, Box<dyn Error>> {
    let mut protos = Vec::new();
    walk(proto_root, &mut protos)?;
    protos.sort();
    Ok(protos)
}

fn walk(dir: &Path, protos: &mut Vec<PathBuf>) -> Result<(), Box<dyn Error>> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            walk(&path, protos)?;
        } else if path.extension().is_some_and(|ext| ext == "proto") {
            protos.push(path);
        }
    }
    Ok(())
}

/// Reads a generated file with line endings normalised, so a CRLF checkout does
/// not read as a diff.
fn read_text(path: &Path) -> std::io::Result<String> {
    Ok(fs::read_to_string(path)?.replace("\r\n", "\n"))
}

fn repo_root() -> Result<PathBuf, Box<dyn Error>> {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let root = manifest_dir
        .parent()
        .ok_or("xtask must live in a subdirectory of the repository")?;
    Ok(root.to_path_buf())
}

fn display_rel(path: &Path, root: &Path) -> String {
    path.strip_prefix(root)
        .unwrap_or(path)
        .display()
        .to_string()
}
